"""命令行层：运行逻辑的唯一实现处，对外只有 `run()` 与 `run_aruco_live()` 两个入口。

用大白话说
    相机（或图片目录、或程序自己画的合成图）会一帧一帧地把画面送进来。
    我们每拿到一帧，就找一次目标（判色 / ArUco 码），在画面上框出来、把结果打到终端。
    两个入口只是"节奏"不同：
        · run()            像交作业：全部跑完再给一份汇总报表（回归测试、离线素材用）
        · run_aruco_live() 像看直播：每来一帧就刷新一次画面，随时可以停（演示用）

包的五个文件（按"读一次要读多少行"切，不是按功能名切）
    parsers.py  参数解析：build_parser / build_live_parser / 共用参数（不碰任何状态）
    run.py      批处理编排：读配置 -> 建源 -> 建检测器 -> 逐帧 -> 汇总
    live.py     实时循环：逐帧 检测 -> 绘制 -> 窗口/落盘 + 终端节流
    report.py   终端输出与自检判定：生效配置、逐帧行、汇总、退出码依据
    __init__.py 只做导出，不写逻辑

    为什么这么切：这四块"改 A 不影响 B"——调参数表不用看逐帧循环，改自检门槛不用翻
    800 行流程。拆之前是一个 847 行的 cli.py，改一条自检逻辑得把整段通读一遍。

依赖谁 / 被谁用
    config -> core -> io -> viz 都在本层之下；本包是它们的唯一上层调用方，不反向依赖。
    被 `python -m up70_vision run|live`（`__main__.py`）调用；
    将来 ROS 2 节点 import 的也是这里的函数，不必抄一份流程。

共同的骨架（两个入口都按这个顺序，顺序本身有原因）
    1. 解析参数      argparse；除了 --help 基本不会失败
    2. 读配置 + 校验  load_config / load_thresholds；失败一律友好报错并返回 2
    3. 建检测器      先建检测器：相机是独占资源，检测器有问题时不该先把相机打开
    4. 建输入源      build_source；相机 / 回放 / 合成三种，失败时释放已建资源
    5. 逐帧循环      read -> detect -> 绘制 -> 输出；异常 / Ctrl+C 都跳到 finally
    6. 收尾          source.close() / destroyAllWindows() / writer.close()
    7. 汇总 + 退出码 0 成功、1 没处理任何帧或落盘失败、2 配置或环境错误

退出码约定（两个入口一致，脚本/CI 靠它判断）
    0  正常跑完
    1  跑了但结果不可用：一帧都没处理、自检不一致、落盘失败
    2  根本没跑起来：配置错、阈值表错、检测器/输入源/窗口建不起来
    其他  Python 未捕获异常（正常路径不该出现）

为什么 print 都写在这一层而不是更下层
    将来 ROS 2 节点 import 的是本包的函数，不应该被迫复用"给终端看"的输出格式，
    也不该让两处各写一份流程；core/io/viz 保持纯算法与 IO，不带终端排版。
"""

from .live import run_aruco_live
from .run import run

__all__ = ["run", "run_aruco_live"]
